  // Уникальные названия блюд из меню в порядке первого появления.
  function dishNames() {
    const seen = {};
    const names = [];
    DATA.menus.forEach((day) => {
      day.forEach((dishes) => {
        dishes.forEach((dish) => {
          if (seen[dish.n]) return;
          seen[dish.n] = true;
          names.push(dish.n);
        });
      });
    });
    return names;
  }

  function get(name) {
    return CATALOG[String(name)] || null;
  }

  // Блюда, у которых ещё нет рецепта: список должен быть пустым.
  function missing() {
    return dishNames().filter((name) => !CATALOG[name]);
  }

  function count() {
    return dishNames().length;
  }

  App.recipes = { get, missing, count };
